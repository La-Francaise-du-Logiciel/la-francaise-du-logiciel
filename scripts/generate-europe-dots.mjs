/**
 * Generates components/europe-dots.ts: a hex-packed dot grid of Europe's
 * actual landmass, rasterized from Natural Earth 50m country polygons.
 *
 * Usage:
 *   curl -sL https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson -o /tmp/ne50m.geojson
 *   node scripts/generate-europe-dots.mjs /tmp/ne50m.geojson
 */

import { readFileSync, writeFileSync } from 'node:fs'

const SRC = process.argv[2] ?? '/tmp/ne50m.geojson'

/* Viewport over Europe (degrees). Equirectangular, x compressed by cos(48.5°).
   Wide enough that the map can bleed to the screen edges: Iceland to the
   west, arctic Norway to the north, western Russia fading out to the east. */
const LON_MIN = -24.0
const LON_MAX = 34.0
const LAT_MIN = 34.0
const LAT_MAX = 66.0
const KLON = Math.cos((48.5 * Math.PI) / 180)

const W_DEG = (LON_MAX - LON_MIN) * KLON
const GRID_W = 1000
const GRID_H = Math.round(((LAT_MAX - LAT_MIN) / W_DEG) * GRID_W)

/* Hex-packed grid spacing in grid units — lower is denser. */
const SPACING = 5.2

const CAPITALS = [
  { name: 'Paris', lon: 2.35, lat: 48.86 },
  { name: 'Berlin', lon: 13.4, lat: 52.52 },
  { name: 'Madrid', lon: -3.7, lat: 40.42 },
  { name: 'Rome', lon: 12.5, lat: 41.9 },
  { name: 'Amsterdam', lon: 4.9, lat: 52.37 },
  { name: 'Brussels', lon: 4.35, lat: 50.85 },
  { name: 'Lisbon', lon: -9.14, lat: 38.72 },
  { name: 'Dublin', lon: -6.26, lat: 53.35 },
  { name: 'Vienna', lon: 16.37, lat: 48.21 },
  { name: 'Warsaw', lon: 21.0, lat: 52.23 },
  { name: 'Stockholm', lon: 18.07, lat: 59.33 },
  { name: 'Copenhagen', lon: 12.57, lat: 55.68 },
  { name: 'Helsinki', lon: 24.94, lat: 60.17 },
  { name: 'Prague', lon: 14.42, lat: 50.09 },
  { name: 'Athens', lon: 23.73, lat: 37.98 },
]

const toGrid = (lon, lat) => ({
  x: (((lon - LON_MIN) * KLON) / W_DEG) * GRID_W,
  y: ((LAT_MAX - lat) / W_DEG) * GRID_W,
})
const toLonLat = (x, y) => ({
  lon: LON_MIN + ((x / GRID_W) * W_DEG) / KLON,
  lat: LAT_MAX - (y / GRID_W) * W_DEG,
})

const geo = JSON.parse(readFileSync(SRC, 'utf8'))
const features = geo.features
  .filter((f) => f.properties.CONTINENT === 'Europe')
  .map((f) => {
    const rings = []
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
    for (const poly of polys) for (const ring of poly) rings.push(ring)
    let minLon = Infinity
    let maxLon = -Infinity
    let minLat = Infinity
    let maxLat = -Infinity
    for (const ring of rings)
      for (const [lon, lat] of ring) {
        if (lon < minLon) minLon = lon
        if (lon > maxLon) maxLon = lon
        if (lat < minLat) minLat = lat
        if (lat > maxLat) maxLat = lat
      }
    return { admin: f.properties.ADMIN, rings, bbox: [minLon, minLat, maxLon, maxLat] }
  })
  .filter(
    (f) =>
      f.bbox[2] >= LON_MIN && f.bbox[0] <= LON_MAX && f.bbox[3] >= LAT_MIN && f.bbox[1] <= LAT_MAX,
  )

console.log('countries in view:', features.map((f) => f.admin).join(', '))

/* Even-odd point-in-polygon across all rings (handles holes). */
const inFeature = (f, lon, lat) => {
  if (lon < f.bbox[0] || lon > f.bbox[2] || lat < f.bbox[1] || lat > f.bbox[3]) return false
  let inside = false
  for (const ring of f.rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i]
      const [xj, yj] = ring[j]
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
    }
  }
  return inside
}

const france = []
const rest = []
const dy = SPACING * 0.866
for (let row = 0, y = SPACING / 2; y < GRID_H; y += dy, row++) {
  for (let x = (row % 2) * (SPACING / 2); x < GRID_W; x += SPACING) {
    const { lon, lat } = toLonLat(x, y)
    const hit = features.find((f) => inFeature(f, lon, lat))
    if (!hit) continue
    const pt = [Math.round(x), Math.round(y)]
    if (hit.admin === 'France') france.push(pt)
    else rest.push(pt)
  }
}

console.log(`dots: ${france.length} France + ${rest.length} rest = ${france.length + rest.length}`)

const nums = [...france.flat(), ...rest.flat()]
const capitals = CAPITALS.map((c) => {
  const { x, y } = toGrid(c.lon, c.lat)
  return { name: c.name, x: Math.round(x), y: Math.round(y) }
})

const out = `/* Generated by scripts/generate-europe-dots.mjs from Natural Earth 50m data — do not edit. */

export const GRID_W = ${GRID_W}
export const GRID_H = ${GRID_H}

/** Number of leading [x, y] pairs in EUROPE_DOTS that belong to France. */
export const FRANCE_COUNT = ${france.length}

/** Flat [x0, y0, x1, y1, …] pairs on the ${GRID_W}×${GRID_H} grid. */
export const EUROPE_DOTS: number[] = [
${chunk(nums, 24)
  .map((c) => '  ' + c.join(', ') + ',')
  .join('\n')}
]

/** Paris first — it anchors the network. */
export const CAPITALS: { name: string; x: number; y: number }[] = [
${capitals.map((c) => `  { name: '${c.name}', x: ${c.x}, y: ${c.y} },`).join('\n')}
]
`

function chunk(arr, size) {
  const out = []
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size))
  return out
}

writeFileSync(new URL('../components/europe-dots.ts', import.meta.url), out)
console.log(`wrote components/europe-dots.ts (${(out.length / 1024).toFixed(0)} KB)`)
